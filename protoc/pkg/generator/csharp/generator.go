func (g *Generator) generatePrxMethod(op *ast.Operation, async bool) string {
	var sb strings.Builder

	returnType := g.toCSharpType(op.ReturnType)
	if returnType == "" {
		returnType = "void"
	}
	hasReturn := returnType != "void"

	// Build parameter list
	var params []string
	var asyncParams []string
	var outParams []*ast.ParamDecl
	for _, p := range op.Params {
		csType := g.toCSharpType(p.Type)
		if p.IsOut {
			outParams = append(outParams, p)
			params = append(params, fmt.Sprintf("out %s %s", csType, p.Name))
		} else {
			params = append(params, fmt.Sprintf("%s %s", csType, p.Name))
			asyncParams = append(asyncParams, fmt.Sprintf("%s %s", csType, p.Name))
		}
	}

	if async {
		asyncReturnType := "Task"
		if hasReturn {
			asyncReturnType = fmt.Sprintf("Task<%s>", returnType)
		}
		sb.WriteString(fmt.Sprintf("        public async %s %sAsync(%s)\n",
			asyncReturnType, op.Name, strings.Join(asyncParams, ", ")))
	} else {
		sb.WriteString(fmt.Sprintf("        public %s %s(%s)\n",
			returnType, op.Name, strings.Join(params, ", ")))
	}

	sb.WriteString("        {\n")

	// Create output stream and write parameters
	sb.WriteString("            var os = new TarsOutputStream();\n")
	tagIndex := 1
	for _, p := range op.Params {
		if !p.IsOut {
			if g.isStructType(p.Type, nil) {
				sb.WriteString(fmt.Sprintf("            os.WriteStruct(%s, %d);\n", p.Name, tagIndex))
			} else if g.isVectorType(p.Type) || g.isMapType(p.Type) {
				sb.WriteString(fmt.Sprintf("            os.Write(%s, %d);\n", p.Name, tagIndex))
			} else {
				sb.WriteString(fmt.Sprintf("            os.Write(%s, %d);\n", p.Name, tagIndex))
			}
		}
		tagIndex++
	}

	// Invoke
	if async {
		sb.WriteString(fmt.Sprintf("            var ist = await InvokeAsync(\"%s\", os);\n", g.toLowerFirst(op.Name)))
	} else {
		sb.WriteString(fmt.Sprintf("            var ist = Invoke(\"%s\", os);\n", g.toLowerFirst(op.Name)))
	}

	// Read out parameters (only for sync methods)
	if !async {
		for _, p := range outParams {
			csType := g.toCSharpType(p.Type)
			// Find the tag index for this out parameter
			outTag := 1
			for _, param := range op.Params {
				if param == p {
					break
				}
				outTag++
			}
			if g.isStructType(p.Type, nil) {
				sb.WriteString(fmt.Sprintf("            %s = ist.Read<%s>(%d, true);\n", p.Name, csType, outTag))
			} else if g.isVectorType(p.Type) {
				sb.WriteString(fmt.Sprintf("            %s = ist.ReadList<%s>(%d, true);\n",
					p.Name, g.getVectorElementType(p.Type), outTag))
			} else if g.isMapType(p.Type) {
				kt, vt := g.getMapKeyValueTypes(p.Type)
				sb.WriteString(fmt.Sprintf("            %s = ist.ReadMap<%s, %s>(%d, true);\n", p.Name, kt, vt, outTag))
			} else {
				sb.WriteString(fmt.Sprintf("            %s = ist.Read(%s, %d, true);\n",
					p.Name, g.getTypeDefaultForRead(p.Type), outTag))
			}
		}
	}

	// Read return value
	if hasReturn {
		if g.isStructType(op.ReturnType, nil) {
			sb.WriteString(fmt.Sprintf("            var ret = ist.Read<%s>(0, true);\n", returnType))
		} else if g.isVectorType(op.ReturnType) {
			sb.WriteString(fmt.Sprintf("            var ret = ist.ReadList<%s>(0, true);\n",
				g.getVectorElementType(op.ReturnType)))
		} else if g.isMapType(op.ReturnType) {
			kt, vt := g.getMapKeyValueTypes(op.ReturnType)
			sb.WriteString(fmt.Sprintf("            var ret = ist.ReadMap<%s, %s>(0, true);\n", kt, vt))
		} else {
			sb.WriteString(fmt.Sprintf("            var ret = ist.Read(%s, 0, true);\n",
				g.getTypeDefaultForRead(op.ReturnType)))
		}
		sb.WriteString("            return ret;\n")
	}

	sb.WriteString("        }\n")

	return sb.String()
}

func (g *Generator) generateServantFile(ns *ast.Namespace, iface *ast.Interface, nsDir string) error {
	var sb strings.Builder

	// File header
	sb.WriteString("// Generated by tarsc - Tars IDL Compiler\n")
	sb.WriteString("// DO NOT EDIT!\n\n")

	sb.WriteString("using System;\n")
	sb.WriteString("using System.Collections.Generic;\n\n")

	sb.WriteString(fmt.Sprintf("namespace %s\n{\n", ns.Name))

	// Servant interface for implementation
	sb.WriteString(fmt.Sprintf("    /// <summary>\n"))
	sb.WriteString(fmt.Sprintf("    /// Servant interface for %s implementation\n", iface.Name))
	sb.WriteString(fmt.Sprintf("    /// </summary>\n"))
	sb.WriteString(fmt.Sprintf("    public interface I%sServant\n    {\n", iface.Name))
	for _, op := range iface.Operations {
		sb.WriteString(g.generateServantInterfaceMethod(op))
	}
	sb.WriteString("    }\n\n")

	// Abstract servant class with dispatch
	sb.WriteString(fmt.Sprintf("    /// <summary>\n"))
	sb.WriteString(fmt.Sprintf("    /// Abstract servant class for %s\n", iface.Name))
	sb.WriteString(fmt.Sprintf("    /// </summary>\n"))
	sb.WriteString(fmt.Sprintf("    public abstract class %sServant : TarsServant, I%sServant\n    {\n", iface.Name, iface.Name))

	// Abstract methods
	for _, op := range iface.Operations {
		sb.WriteString(g.generateServantAbstractMethod(op))
		sb.WriteString("\n")
	}

	// Dispatch method
	sb.WriteString("        /// <summary>\n")
	sb.WriteString("        /// Dispatch incoming request to appropriate method\n")
	sb.WriteString("        /// </summary>\n")
	sb.WriteString("        public override byte[] Dispatch(string funcName, byte[] request)\n")
	sb.WriteString("        {\n")
	sb.WriteString("            var ist = new TarsInputStream(request);\n")
	sb.WriteString("            var os = new TarsOutputStream();\n\n")
	sb.WriteString("            switch (funcName)\n")
	sb.WriteString("            {\n")

	for _, op := range iface.Operations {
		sb.WriteString(g.generateDispatchCase(op))
	}

	sb.WriteString("                default:\n")
	sb.WriteString("                    throw new NotSupportedException($\"Unknown function: {funcName}\");\n")
	sb.WriteString("            }\n\n")
	sb.WriteString("            return os.ToByteArray();\n")
	sb.WriteString("        }\n")

	sb.WriteString("    }\n")
	sb.WriteString("}\n")

	// Write file
	filePath := filepath.Join(nsDir, iface.Name+"Servant.cs")
	return os.WriteFile(filePath, []byte(sb.String()), 0644)
}

