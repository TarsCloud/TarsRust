func (g *Generator) generateDispatchCase(op *ast.Operation) string {
	var sb strings.Builder

	returnType := g.toCSharpType(op.ReturnType)
	if returnType == "" {
		returnType = "void"
	}
	hasReturn := returnType != "void"

	sb.WriteString(fmt.Sprintf("                case \"%s\":\n", g.toLowerFirst(op.Name)))
	sb.WriteString("                {\n")

	// Read input parameters
	tagIndex := 1
	var callArgs []string
	for _, p := range op.Params {
		csType := g.toCSharpType(p.Type)
		if p.IsOut {
			sb.WriteString(fmt.Sprintf("                    %s %s;\n", csType, p.Name))
			callArgs = append(callArgs, fmt.Sprintf("out %s", p.Name))
		} else {
			if g.isStructType(p.Type, nil) {
				sb.WriteString(fmt.Sprintf("                    var %s = ist.Read<%s>(%d, true);\n", p.Name, csType, tagIndex))
			} else if g.isVectorType(p.Type) {
				sb.WriteString(fmt.Sprintf("                    var %s = ist.ReadList<%s>(%d, true);\n",
					p.Name, g.getVectorElementType(p.Type), tagIndex))
			} else if g.isMapType(p.Type) {
				kt, vt := g.getMapKeyValueTypes(p.Type)
				sb.WriteString(fmt.Sprintf("                    var %s = ist.ReadMap<%s, %s>(%d, true);\n", p.Name, kt, vt, tagIndex))
			} else {
				sb.WriteString(fmt.Sprintf("                    var %s = ist.Read(%s, %d, true);\n",
					p.Name, g.getTypeDefaultForRead(p.Type), tagIndex))
			}
			callArgs = append(callArgs, p.Name)
		}
		tagIndex++
	}

	// Call method
	if hasReturn {
		sb.WriteString(fmt.Sprintf("                    var result = %s(%s);\n", op.Name, strings.Join(callArgs, ", ")))
	} else {
		sb.WriteString(fmt.Sprintf("                    %s(%s);\n", op.Name, strings.Join(callArgs, ", ")))
	}

	// Write return value
	if hasReturn {
		if g.isStructType(op.ReturnType, nil) {
			sb.WriteString("                    os.WriteStruct(result, 0);\n")
		} else {
			sb.WriteString("                    os.Write(result, 0);\n")
		}
	}

	// Write out parameters
	tagIndex = 1
	for _, p := range op.Params {
		if p.IsOut {
			if g.isStructType(p.Type, nil) {
				sb.WriteString(fmt.Sprintf("                    os.WriteStruct(%s, %d);\n", p.Name, tagIndex))
			} else {
				sb.WriteString(fmt.Sprintf("                    os.Write(%s, %d);\n", p.Name, tagIndex))
			}
		}
		tagIndex++
	}

	sb.WriteString("                    break;\n")
	sb.WriteString("                }\n")

	return sb.String()
}

// Helper methods

func (g *Generator) toCSharpType(t ast.Type) string {
	if t == nil {
		return "void"
	}

	switch v := t.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindVoid:
			return "void"
		case ast.KindBool:
			return "bool"
		case ast.KindByte:
			if v.IsUnsigned {
				return "byte"
			}
			return "sbyte"
		case ast.KindShort:
			if v.IsUnsigned {
				return "ushort"
			}
			return "short"
		case ast.KindInt:
			if v.IsUnsigned {
				return "uint"
			}
			return "int"
		case ast.KindLong:
			if v.IsUnsigned {
				return "ulong"
			}
			return "long"
		case ast.KindFloat:
			return "float"
		case ast.KindDouble:
			return "double"
		case ast.KindString:
			return "string"
		}
	case *ast.VectorType:
		if bt, ok := v.ElementType.(*ast.BuiltinType); ok && bt.Kind == ast.KindByte {
			return "byte[]"
		}
		return fmt.Sprintf("List<%s>", g.toCSharpType(v.ElementType))
	case *ast.MapType:
		return fmt.Sprintf("Dictionary<%s, %s>", g.toCSharpType(v.KeyType), g.toCSharpType(v.ValueType))
	case *ast.CustomType:
		return v.TypeName_
	}
	return "object"
}

func (g *Generator) toCSharpFieldName(name string) string {
	if len(name) == 0 {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func (g *Generator) toPascalCase(name string) string {
	if len(name) == 0 {
		return name
	}
	// Handle underscore separated names
	parts := strings.Split(name, "_")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func (g *Generator) toLowerFirst(name string) string {
	if len(name) == 0 {
		return name
	}
	return strings.ToLower(name[:1]) + name[1:]
}

func (g *Generator) getCSharpDefault(f *ast.Field, ns *ast.Namespace) string {
	if f.DefaultValue == "" {
		return g.getTypeDefault(f.Type)
	}

	switch v := f.Type.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindString:
			// Ensure string is quoted
			if !strings.HasPrefix(f.DefaultValue, "\"") {
				return fmt.Sprintf("\"%s\"", f.DefaultValue)
			}
			return f.DefaultValue
		case ast.KindFloat:
			return f.DefaultValue + "f"
		default:
			return f.DefaultValue
		}
	case *ast.CustomType:
		// Check if it's an enum reference
		if ns != nil {
			for _, e := range ns.Enums {
				for _, m := range e.Members {
					if m.Name == f.DefaultValue {
						return fmt.Sprintf("%s.%s", e.Name, m.Name)
					}
				}
			}
		}
		return f.DefaultValue
	}
	return f.DefaultValue
}

func (g *Generator) getTypeDefault(t ast.Type) string {
	if t == nil {
		return ""
	}

	switch v := t.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindBool:
			return "false"
		case ast.KindString:
			return "\"\""
		case ast.KindByte, ast.KindShort, ast.KindInt, ast.KindLong:
			return "0"
		case ast.KindFloat:
			return "0.0f"
		case ast.KindDouble:
			return "0.0"
		}
	case *ast.VectorType:
		return fmt.Sprintf("new %s()", g.toCSharpType(t))
	case *ast.MapType:
		return fmt.Sprintf("new %s()", g.toCSharpType(t))
	case *ast.CustomType:
		return fmt.Sprintf("new %s()", v.TypeName_)
	}
	return ""
}

func (g *Generator) getTypeDefaultForRead(t ast.Type) string {
	if t == nil {
		return "0"
	}

	switch v := t.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindBool:
			return "false"
		case ast.KindString:
			return "\"\""
		case ast.KindByte, ast.KindShort, ast.KindInt, ast.KindLong:
			return "0"
		case ast.KindFloat:
			return "0f"
		case ast.KindDouble:
			return "0d"
		}
	case *ast.CustomType:
		// Enum defaults
		return "0"
	}
	return "0"
}

func (g *Generator) isStructType(t ast.Type, ns *ast.Namespace) bool {
	if ct, ok := t.(*ast.CustomType); ok {
		// If namespace is provided, check if it's an enum
		if ns != nil {
			for _, e := range ns.Enums {
				if e.Name == ct.TypeName_ {
					return false
				}
			}
		}
		// Assume custom types that are not enums are structs
		return true
	}
	return false
}

func (g *Generator) isEnumType(t ast.Type, ns *ast.Namespace) bool {
	if ct, ok := t.(*ast.CustomType); ok {
		// Check if it's an enum
		if ns != nil {
			for _, e := range ns.Enums {
				if e.Name == ct.TypeName_ {
					return true
				}
			}
		}
	}
	return false
}

func (g *Generator) isVectorType(t ast.Type) bool {
	_, ok := t.(*ast.VectorType)
	return ok
}

func (g *Generator) isMapType(t ast.Type) bool {
	_, ok := t.(*ast.MapType)
	return ok
}

func (g *Generator) getVectorElementType(t ast.Type) string {
	if vt, ok := t.(*ast.VectorType); ok {
		return g.toCSharpType(vt.ElementType)
	}
	return "object"
}

func (g *Generator) getMapKeyValueTypes(t ast.Type) (string, string) {
	if mt, ok := t.(*ast.MapType); ok {
		return g.toCSharpType(mt.KeyType), g.toCSharpType(mt.ValueType)
	}
	return "object", "object"
}
