func (g *Generator) operationParams(params []*ast.ParamDecl, afterParams []string, isSync bool) string {
	return g.operationParamsWithPrefix(nil, params, afterParams, isSync)
}

func (g *Generator) operationParamsWithPrefix(beforeParams []string, params []*ast.ParamDecl, afterParams []string, isSync bool) string {
	var parts []string

	for _, bp := range beforeParams {
		parts = append(parts, bp)
	}

	for _, p := range params {
		if !isSync && p.IsOut {
			continue
		}

		javaType := g.toJavaType(p.Type)
		annotation := ""

		if p.IsOut {
			annotation = fmt.Sprintf("@TarsHolder(name=\"%s\") ", p.Name)
			javaType = fmt.Sprintf("Holder<%s>", g.toJavaBoxedType(p.Type))
		} else {
			annotation = fmt.Sprintf("@TarsMethodParameter(name=\"%s\") ", p.Name)
			if p.IsRouteKey {
				annotation = "@TarsRouteKey " + annotation
			}
		}

		parts = append(parts, fmt.Sprintf("%s%s %s", annotation, javaType, p.Name))
	}

	for _, ap := range afterParams {
		parts = append(parts, ap)
	}

	return strings.Join(parts, ", ")
}

func (g *Generator) callbackParams(op *ast.Operation) string {
	var parts []string

	for _, p := range op.Params {
		if p.IsOut {
			javaType := g.toJavaType(p.Type)
			parts = append(parts, fmt.Sprintf("%s %s", javaType, p.Name))
		}
	}

	return strings.Join(parts, ", ")
}

func (g *Generator) toJavaType(t ast.Type) string {
	switch v := t.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindVoid:
			return "void"
		case ast.KindBool:
			return "boolean"
		case ast.KindByte:
			return "byte"
		case ast.KindShort:
			if v.IsUnsigned {
				return "int"
			}
			return "short"
		case ast.KindInt:
			if v.IsUnsigned {
				return "long"
			}
			return "int"
		case ast.KindLong:
			return "long"
		case ast.KindFloat:
			return "float"
		case ast.KindDouble:
			return "double"
		case ast.KindString:
			return "String"
		}
	case *ast.VectorType:
		if bt, ok := v.ElementType.(*ast.BuiltinType); ok && bt.Kind == ast.KindByte {
			return "byte[]"
		}
		return fmt.Sprintf("java.util.List<%s>", g.toJavaBoxedType(v.ElementType))
	case *ast.MapType:
		return fmt.Sprintf("java.util.Map<%s, %s>", g.toJavaBoxedType(v.KeyType), g.toJavaBoxedType(v.ValueType))
	case *ast.CustomType:
		if g.isEnum(t) {
			return "int"
		}
		return v.TypeName_
	}
	return "Object"
}

func (g *Generator) toJavaBoxedType(t ast.Type) string {
	switch v := t.(type) {
	case *ast.BuiltinType:
		switch v.Kind {
		case ast.KindVoid:
			return "Void"
		case ast.KindBool:
			return "Boolean"
		case ast.KindByte:
			return "Byte"
		case ast.KindShort:
			if v.IsUnsigned {
				return "Integer"
			}
			return "Short"
		case ast.KindInt:
			if v.IsUnsigned {
				return "Long"
			}
			return "Integer"
		case ast.KindLong:
			return "Long"
		case ast.KindFloat:
			return "Float"
		case ast.KindDouble:
			return "Double"
		case ast.KindString:
			return "String"
		}
	case *ast.CustomType:
		if g.isEnum(t) {
			return "Integer"
		}
	}
	return g.toJavaType(t)
}

func (g *Generator) getBuiltinDefault(bt *ast.BuiltinType, useDefault bool) string {
	switch bt.Kind {
	case ast.KindBool:
		return "false"
	case ast.KindString:
		return "\"\""
	case ast.KindByte:
		return "(byte)0"
	case ast.KindShort:
		return "(short)0"
	case ast.KindInt:
		return "0"
	case ast.KindLong:
		return "0L"
	case ast.KindFloat:
		return "0.0f"
	case ast.KindDouble:
		return "0.0"
	}
	return "null"
}

func (g *Generator) getJavaDefault(f *ast.Field) string {
	if f.HasDefault && f.DefaultValue != "" {
		value := f.DefaultValue
		if bt, ok := f.Type.(*ast.BuiltinType); ok {
			switch bt.Kind {
			case ast.KindLong:
				if !strings.HasSuffix(value, "L") && !strings.HasSuffix(value, "l") {
					value += "L"
				}
			case ast.KindFloat:
				if !strings.HasSuffix(value, "F") && !strings.HasSuffix(value, "f") {
					value += "F"
				}
			case ast.KindDouble:
				if !strings.HasSuffix(value, "D") && !strings.HasSuffix(value, "d") {
					value += "D"
				}
			}
		}
		return value
	}

	return g.getJavaTypeDefault(f.Type)
}

func (g *Generator) getJavaTypeDefault(t ast.Type) string {
	switch v := t.(type) {
	case *ast.BuiltinType:
		return g.getBuiltinDefault(v, false)
	case *ast.VectorType:
		if bt, ok := v.ElementType.(*ast.BuiltinType); ok && bt.Kind == ast.KindByte {
			return "null"
		}
		return "new java.util.ArrayList<>()"
	case *ast.MapType:
		return "new java.util.HashMap<>()"
	case *ast.CustomType:
		if g.isEnum(t) {
			return "0"
		}
		return "new " + v.TypeName_ + "()"
	}
	return "null"
}

func (g *Generator) typeCanBeNull(t ast.Type) bool {
	if ct, ok := t.(*ast.CustomType); ok {
		if g.isEnum(t) {
			return false
		}
		_ = ct
		return true
	}
	if bt, ok := t.(*ast.BuiltinType); ok {
		return bt.Kind == ast.KindString
	}
	return true
}

func (g *Generator) isEnum(t ast.Type) bool {
	if ct, ok := t.(*ast.CustomType); ok {
		return g.enums[ct.Name] || g.enums[ct.TypeName_]
	}
	return false
}

